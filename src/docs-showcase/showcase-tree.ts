import type { DocsSnippet } from './extract-snippets.ts';
import type {
  KnownModuleExports,
  PageModule,
  SnippetKind
} from './wrap-snippet.ts';

import {
  HOST_SPECIFIER,
  wrapSnippet
} from './wrap-snippet.ts';

/** One snippet as the showcase builds it: the report's record, plus the code and module the sync works with. */
export interface ShowcaseEntry extends ShowcaseReportEntry {
  /** The block's code. Not written to the report. */
  readonly code: string;
  /** The wrapped module, before the type check decides whether it ships. Not written to the report. */
  readonly module: string;
}

/** One snippet as `snippets.json` records it: where it came from, what it is, and whether it made it in. */
export interface ShowcaseReportEntry {
  /** The TypeScript diagnostics that kept it out, as `line:column code: message`, against its module. */
  // eslint-disable-next-line typescript-dev-toolkit/readonly-interface-members -- The sync updates the report after type-checking each snippet.
  diagnostics: string[];
  /** The module's path below `src/docs/`, or empty when it has none. */
  readonly file: string;
  readonly headings: readonly string[];
  /** Unique within the showcase: the page's slug and the block's position on the page. */
  readonly id: string;
  readonly kind: SnippetKind;
  readonly lang: string;
  readonly line: number;
  /** The command name. */
  readonly name: string;
  readonly page: string;
  /** Why it is not runnable or why it failed. Empty when it is runnable. */
  // eslint-disable-next-line typescript-dev-toolkit/readonly-interface-members -- The sync updates the report after type-checking each snippet.
  reason: string;
  // eslint-disable-next-line typescript-dev-toolkit/readonly-interface-members -- The sync updates the report after type-checking each snippet.
  status: SnippetStatus;
}

/** The upstream commit the snippets were read at, and its license notice, which every module's header repeats. */
export interface ShowcaseSource {
  readonly commit: string;
  /** The license notice `describeUpstreamLicense` reads from upstream's `LICENSE`, or empty when it has none. */
  readonly license: string;
  readonly repo: string;
}

/** Where a snippet ended up. */
export type SnippetStatus = 'not-runnable' | 'runnable' | 'type-error';

/** A snippet with the module path and id it is given. */
interface PlacedSnippet {
  readonly file: string;
  readonly id: string;
  readonly snippet: DocsSnippet;
}

const DOCS_SITE = 'https://docs.obsidian.md';
const SHORT_COMMIT_LENGTH = 7;
/** How many leading path segments of a page name its docs section: `Plugins/Editor`. */
const SECTION_DEPTH = 2;
/** The suffix the second command with a given name gets: `Vault > Read files (2)`. */
const FIRST_DUPLICATE_SUFFIX = 2;
const MAX_SLUG_LENGTH = 40;
const POSITION_DIGITS = 2;

/**
 * The generated `index.ts`: one lazily loaded entry per runnable snippet.
 *
 * @param entries - Every entry; only the runnable ones are listed.
 * @returns The module source.
 */
export function buildIndexModule(entries: readonly ShowcaseEntry[]): string {
  const runnable = entries.filter((entry) => entry.status === 'runnable');
  const lines = [
    '// Generated by create-obsidian-plugin from the Obsidian developer docs. One command per runnable code block;',
    '// `README.md` in this folder lists every block, including the ones that are not here and why.',
    '',
    'import type { Plugin } from \'obsidian\';',
    '',
    'import type { DocsEntry } from \'./host.ts\';',
    '',
    'import { registerDocsEntries } from \'./host.ts\';',
    '',
    'const ENTRIES: DocsEntry[] = ['
  ];
  for (const [index, entry] of runnable.entries()) {
    lines.push(
      '  {',
      `    id: ${JSON.stringify(entry.id)},`,
      `    load: () => import(${JSON.stringify(`./${entry.file}`)}),`,
      `    name: ${JSON.stringify(entry.name)},`,
      `    source: ${JSON.stringify(docsUrl(entry.page, entry.headings))}`,
      index === runnable.length - 1 ? '  }' : '  },'
    );
  }
  lines.push(
    '];',
    '',
    'export function registerDocsShowcase(plugin: Plugin): void {',
    '  registerDocsEntries(plugin, ENTRIES);',
    '}',
    ''
  );
  return lines.join('\n');
}

/**
 * The generated `README.md` of the showcase folder: every code block of the docs, grouped by page, with its command
 * or the reason it has none.
 *
 * @param entries - Every entry.
 * @param source - The upstream commit and license.
 * @returns The Markdown.
 */
export function buildReadme(entries: readonly ShowcaseEntry[], source: ShowcaseSource): string {
  const runnableCount = entries.filter((entry) => entry.status === 'runnable').length;
  const failedCount = entries.filter((entry) => entry.status === 'type-error').length;
  const notRunnableCount = entries.filter((entry) => entry.status === 'not-runnable').length;
  const lines = [
    '# Developer docs showcase',
    '',
    `Every code block of the [Obsidian developer docs](${DOCS_SITE}), taken from [${source.repo}](https://github.com/${source.repo}) at commit [\`${source.commit.slice(0, SHORT_COMMIT_LENGTH)}\`](https://github.com/${source.repo}/tree/${source.commit}). Each runnable block is a command named \`Docs: <page> > <heading>\`: open the command palette, type \`Docs:\`, and run it.`,
    '',
    `${String(runnableCount)} blocks are runnable. ${String(failedCount)} do not compile against the \`obsidian\` API, and ${String(notRunnableCount)} are not plugin code. Both kinds are listed below with the reason, so nothing is dropped silently.`,
    '',
    'Each module holds the block as the docs show it, plus what create-obsidian-plugin generated around it: the imports the block leaves out, an export list for the blocks after it on the same page, and a `run(context)` function. `host.ts` supplies what the docs leave to the reader: a plugin to register things on, a scratch note to work with, an editor, an element to draw into.',
    '',
    'The modules are type-checked by `tsconfig.json` in this folder, which carries the compiler options of the official sample plugin, rather than by the project\'s own stricter `tsconfig.json`. They are upstream\'s code, so the project\'s linter, formatter and spell checker skip this folder.',
    ''
  ];
  if (source.license !== '') {
    lines.push(`The code blocks are licensed under ${source.license}. See the [LICENSE](https://github.com/${source.repo}/blob/${source.commit}/LICENSE).`, '');
  }

  let page = '';
  for (const entry of entries) {
    if (entry.page !== page) {
      page = entry.page;
      lines.push(`## ${entry.page.replaceAll('/', ' > ')}`, '', `Docs page: <${docsUrl(entry.page, [])}>`, '');
    }
    lines.push(`- ${describeEntry(entry, source)}`);
    const nextEntry = entries[entries.indexOf(entry) + 1];
    if (nextEntry?.page !== page) {
      lines.push('');
    }
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

/**
 * Classifies and wraps every snippet, giving each its id, command name and module path.
 *
 * A block often uses a name another block declares: `EmojiWidget` is declared in one block of the Decorations page
 * and used in the next, and the Communicating with editor extensions page uses the `examplePlugin` the View plugins
 * page declares. Such a name is imported from the block that declares it, looked for first among the blocks before
 * it on the same page (nearest first), then the blocks after it, then the other pages of the same docs section
 * (`Plugins/Editor`). So the snippets are wrapped twice: once to learn what each module exports, and once more with
 * those exports known.
 *
 * @param snippets - The snippets, in page order and then line order.
 * @param knownModules - The packages a missing name can come from.
 * @param source - The upstream commit and license.
 * @returns One entry per snippet, every one of them `runnable` or `not-runnable` until the type check runs.
 */
export function buildShowcaseEntries(snippets: readonly DocsSnippet[], knownModules: KnownModuleExports, source: ShowcaseSource): ShowcaseEntry[] {
  const placed = placeSnippets(snippets);
  const providers = placed.map(({ file, snippet }) => ({ exports: wrapSnippet(snippet, knownModules, []).exports, file, snippet }));
  const usedNames = new Set<string>();

  return placed.map(({ file, id, snippet }, index) => {
    const section = sectionOf(snippet.page);
    const candidates = [
      ...providers.slice(0, index).filter((provider) => provider.snippet.page === snippet.page).reverse(),
      ...providers.slice(index + 1).filter((provider) => provider.snippet.page === snippet.page),
      ...providers.filter((provider) => provider.snippet.page !== snippet.page && sectionOf(provider.snippet.page) === section)
    ];
    const pageModules: PageModule[] = candidates
      .filter((provider) => provider.exports.length > 0)
      .map((provider) => ({ exports: provider.exports, specifier: relativeSpecifier(file, provider.file) }));
    const wrapped = wrapSnippet(snippet, knownModules, pageModules);
    const name = uniqueName(commandName(snippet), usedNames);
    const isRunnable = wrapped.kind !== 'not-runnable';

    return {
      code: snippet.code,
      diagnostics: [],
      file: isRunnable ? file : '',
      headings: snippet.headings,
      id,
      kind: wrapped.kind,
      lang: snippet.lang,
      line: snippet.line,
      module: isRunnable ? `${moduleHeader(snippet, name, source)}${wrapped.module.replaceAll(`'${HOST_SPECIFIER}'`, `'${relativeSpecifier(file, 'host.ts')}'`)}` : '',
      name,
      page: snippet.page,
      reason: wrapped.reason,
      status: isRunnable ? 'runnable' : 'not-runnable'
    };
  });
}

/**
 * The docs page URL of a snippet, with the anchor of the heading it sits under.
 *
 * @param page - The page path below `en/`.
 * @param headings - The headings above the snippet.
 * @returns The URL.
 */
export function docsUrl(page: string, headings: readonly string[]): string {
  const heading = headings.at(-1);
  const anchor = heading === undefined ? '' : `#${encodeDocsSegment(heading)}`;
  return `${DOCS_SITE}/${page.split('/').map(encodeDocsSegment).join('/')}${anchor}`;
}

/**
 * The URL of a snippet's block in the upstream repository.
 *
 * @param entry - The snippet's page and line.
 * @param source - The upstream commit.
 * @returns The URL.
 */
export function upstreamUrl(entry: Pick<ShowcaseEntry, 'line' | 'page'>, source: ShowcaseSource): string {
  const path = `en/${entry.page}.md`.split('/').map(encodeURIComponent).join('/');
  return `https://github.com/${source.repo}/blob/${source.commit}/${path}?plain=1#L${String(entry.line)}`;
}

/** The command name: the page title and the headings above the block, as plain text. */
function commandName(snippet: DocsSnippet): string {
  const pageTitle = snippet.page.split('/').at(-1) ?? snippet.page;
  const headings = snippet.headings.map(toPlainText).filter((heading) => heading !== pageTitle);
  return [pageTitle, ...headings].join(' > ');
}

function describeEntry(entry: ShowcaseEntry, source: ShowcaseSource): string {
  const block = `[block at line ${String(entry.line)}](${upstreamUrl(entry, source)})${entry.headings.length > 0 ? ` under "${entry.headings.join(' > ')}"` : ''}`;
  const outcomes: Record<SnippetStatus, string> = {
    'not-runnable': `not runnable, ${entry.reason}`,
    'runnable': `command \`Docs: ${entry.name}\`, module \`${entry.file}\``,
    'type-error': `does not compile, ${entry.reason}`
  };
  return `${block}: ${outcomes[entry.status]}.`;
}

function encodeDocsSegment(segment: string): string {
  return encodeURIComponent(segment).replaceAll('%20', '+');
}

function moduleHeader(snippet: DocsSnippet, name: string, source: ShowcaseSource): string {
  const lines = [
    `// Docs: ${name}`,
    `// ${docsUrl(snippet.page, snippet.headings)}`,
    `// Source: ${upstreamUrl(snippet, source)}`
  ];
  if (source.license !== '') {
    lines.push(`// The code block is licensed under ${source.license}.`);
  }
  lines.push(
    '// The code block is upstream\'s, as the docs show it. create-obsidian-plugin generated the rest: the imports it',
    '// leaves out, the exports later blocks on the page take, and the `run(context)` host the command calls.',
    ''
  );
  return `${lines.join('\n')}\n`;
}

/** Gives each snippet its id and module path: the page's folder, and the block's position on the page. */
function placeSnippets(snippets: readonly DocsSnippet[]): PlacedSnippet[] {
  const positions = new Map<string, number>();
  return snippets.map((snippet) => {
    const position = String((positions.get(snippet.page) ?? 0) + 1).padStart(POSITION_DIGITS, '0');
    positions.set(snippet.page, Number(position));
    const pageDir = snippet.page.split('/').map((segment) => slugify(segment, Infinity)).join('/');
    const heading = slugify(snippet.headings.at(-1) ?? '', MAX_SLUG_LENGTH) || 'intro';
    return {
      file: `${pageDir}/${position}-${heading}.ts`,
      id: `${slugify(snippet.page.replaceAll('/', '-'), Infinity)}-${position}`,
      snippet
    };
  });
}

/**
 * The specifier one module of the showcase imports another by.
 *
 * @param fromFile - The importing module, below `src/docs/`.
 * @param toFile - The imported module, below `src/docs/`.
 * @returns A relative specifier, always starting with `./` or `../`.
 */
function relativeSpecifier(fromFile: string, toFile: string): string {
  const fromParts = fromFile.split('/').slice(0, -1);
  const toParts = toFile.split('/');
  let common = 0;
  while (common < fromParts.length && common < toParts.length - 1 && fromParts[common] === toParts[common]) {
    common++;
  }
  const up = fromParts.length - common;
  const rest = toParts.slice(common).join('/');
  return up === 0 ? `./${rest}` : `${'../'.repeat(up)}${rest}`;
}

/** The docs section a page belongs to: its first two path segments, such as `Plugins/Editor`. */
function sectionOf(page: string): string {
  return page.split('/').slice(0, SECTION_DEPTH).join('/');
}

function slugify(text: string, maxLength: number): string {
  const slug = text.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-').replaceAll(/^-+|-+$/g, '');
  return slug.length > maxLength ? slug.slice(0, maxLength).replace(/-+$/, '') : slug;
}

/** A heading as plain text: code spans and links unwrapped, so it reads as a command name and nests in a code span. */
function toPlainText(heading: string): string {
  return heading.replaceAll(/\[(?<Text>[^\]]*)\]\([^)]*\)/g, '$<Text>').replaceAll('`', '');
}

function uniqueName(name: string, usedNames: Set<string>): string {
  let candidate = name;
  for (let suffix = FIRST_DUPLICATE_SUFFIX; usedNames.has(candidate); suffix++) {
    candidate = `${name} (${String(suffix)})`;
  }
  usedNames.add(candidate);
  return candidate;
}
