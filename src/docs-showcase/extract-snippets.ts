/** One fenced code block found in a page of obsidianmd/obsidian-developer-docs. */
export interface DocsSnippet {
  /** The block's content, with the fence's own indentation removed from every line. */
  readonly code: string;
  /** The headings the block sits under, outermost first. A page with no heading above the block gives none. */
  readonly headings: readonly string[];
  /** The fence's info string language, lowercased. Empty when the fence names none. */
  readonly lang: string;
  /** The 1-based line of the opening fence in the page. */
  readonly line: number;
  /** The page's path below `en/`, without `.md`: `Plugins/Vault`. */
  readonly page: string;
  /** The `title="..."` attribute of the fence, when it has one: the file name the docs give the block. */
  readonly title: string;
}

/** A fenced block as read from its lines, before the page and the headings above it are attached. */
interface FencedBlock {
  /** The index of the closing fence's line, or of the last line when the block is never closed. */
  readonly endIndex: number;
  readonly snippet: Pick<DocsSnippet, 'code' | 'lang' | 'line' | 'title'>;
}

/** The pages the snippets are read from: everything below this folder of the upstream repository. */
export const DOCS_CONTENT_DIR = 'en';

const SIGNATURE_MARKER = '**Signature:**';

const MIN_FENCE_LENGTH = 3;

/**
 * Every fenced code block in the given pages, in page order and then line order.
 *
 * The TypeScript API reference pages are generated by API Documenter, and each opens its member with a
 * `**Signature:**` paragraph followed by the declaration. Those ~1200 blocks are declarations of the API itself,
 * not code a reader runs, so a block directly under that marker is not a snippet. Every other block is returned,
 * whatever its language: deciding what is runnable is the classifier's job, and a block it cannot run is listed
 * with the reason rather than dropped here.
 *
 * @param pages - Each page's path below `en/` (with `.md`) and its text.
 * @returns The snippets.
 */
export function extractSnippets(pages: ReadonlyMap<string, string>): DocsSnippet[] {
  const snippets: DocsSnippet[] = [];
  const sortedPaths = [...pages.keys()].filter((path) => path.endsWith('.md')).sort((a, b) => a.localeCompare(b));
  for (const path of sortedPaths) {
    snippets.push(...extractPageSnippets(path.slice(0, -'.md'.length), pages.get(path) ?? ''));
  }
  return snippets;
}

function extractPageSnippets(page: string, pageText: string): DocsSnippet[] {
  const lines = pageText.split(/\r?\n/);
  const snippets: DocsSnippet[] = [];
  const headings: string[] = [];
  let previousText = '';

  for (let index = skipFrontmatter(lines); index < lines.length; index++) {
    const line = lines[index] ?? '';
    const fence = readFence(lines, index);
    if (fence) {
      if (previousText !== SIGNATURE_MARKER) {
        snippets.push({ ...fence.snippet, headings: headings.filter((heading) => heading !== ''), page });
      }
      index = fence.endIndex;
      previousText = '';
      continue;
    }

    updateHeadings(headings, line);
    if (line.trim() !== '') {
      previousText = line.trim();
    }
  }

  return snippets;
}

function isClosingFence(line: string, fence: string): boolean {
  const trimmed = line.trim();
  const fenceChar = fence[0] ?? '`';
  return trimmed.length >= Math.max(fence.length, MIN_FENCE_LENGTH) && trimmed.replaceAll(fenceChar, '') === '';
}

/** Reads the fenced block opening at `index`, or returns `null` when the line opens none. */
function readFence(lines: readonly string[], index: number): FencedBlock | null {
  const opening = /^(?<Indent>\s*)(?<Fence>`{3,}|~{3,})\s*(?<Info>.*)$/.exec(lines[index] ?? '')?.groups;
  if (!opening) {
    return null;
  }
  const indent = opening['Indent'] ?? '';
  const fence = opening['Fence'] ?? '';
  const info = (opening['Info'] ?? '').trim();
  const body: string[] = [];
  let endIndex = index + 1;
  while (endIndex < lines.length && !isClosingFence(lines[endIndex] ?? '', fence)) {
    body.push(stripIndent(lines[endIndex] ?? '', indent));
    endIndex++;
  }
  return {
    endIndex,
    snippet: {
      code: trimBlankLines(body).join('\n'),
      lang: (/^[\w+-]*/.exec(info)?.[0] ?? '').toLowerCase(),
      line: index + 1,
      title: /title="(?<Title>[^"]*)"/.exec(info)?.groups?.['Title'] ?? ''
    }
  };
}

/** The index of the first line after the page's YAML frontmatter, or 0 when it has none. */
function skipFrontmatter(lines: readonly string[]): number {
  if (lines[0] !== '---') {
    return 0;
  }
  const closing = lines.indexOf('---', 1);
  return closing === -1 ? 0 : closing + 1;
}

function stripIndent(line: string, indent: string): string {
  let removed = 0;
  while (removed < indent.length && (line[removed] === ' ' || line[removed] === '\t')) {
    removed++;
  }
  return line.slice(removed);
}

function trimBlankLines(lines: string[]): string[] {
  let start = 0;
  let end = lines.length;
  while (start < end && (lines[start] ?? '').trim() === '') {
    start++;
  }
  while (end > start && (lines[end - 1] ?? '').trim() === '') {
    end--;
  }
  return lines.slice(start, end).map((line) => line.trimEnd());
}

/** Keeps `headings` the path of headings above the current line, outermost first, with a gap left empty. */
function updateHeadings(headings: string[], line: string): void {
  const heading = /^(?<Level>#{1,6})\s+(?<Text>.+?)\s*#*\s*$/.exec(line)?.groups;
  if (!heading) {
    return;
  }
  const level = (heading['Level'] ?? '#').length;
  headings.length = Math.min(headings.length, level - 1);
  while (headings.length < level - 1) {
    headings.push('');
  }
  headings.push(heading['Text'] ?? '');
}
